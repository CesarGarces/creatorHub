// Regenerates src/i18n/messages/<locale>/index.ts from the namespace files.
// Usage: node scripts/gen-i18n-index.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/i18n/messages",
);
const locales = ["en", "es", "pt"];
const namespaces = readdirSync(join(root, "en"))
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

for (const locale of locales) {
  const imports = namespaces
    .map((ns) => `import { ${ns} } from "./${ns}";`)
    .join("\n");
  const typeImport =
    locale === "en" ? "" : `import type { Messages } from "../../translate";\n`;
  const annotation = locale === "en" ? "" : ": Messages";
  const body = `// AUTO-GENERATED by scripts/gen-i18n-index.mjs — do not edit by hand.\n${typeImport}${imports}\n\nexport const ${locale}${annotation} = {\n${namespaces
    .map((ns) => `  ${ns},`)
    .join("\n")}\n};\n`;
  writeFileSync(join(root, locale, "index.ts"), body);
}
console.log(`Generated index for ${namespaces.length} namespaces.`);
